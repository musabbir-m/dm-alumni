import mongoose, { Schema, type InferSchemaType, type Model } from 'mongoose';
import { ELECTION_STATUSES } from '@/lib/election-fields';

/**
 * A committee election. One at a time in practice (the one-open rule is
 * enforced in src/lib/election.ts, not by a partial-unique index — the shared
 * Atlas DB may legitimately hold an old published election beside a new
 * draft). Candidates embed an identity snapshot refreshed from the User
 * record on every config save (the PaymentWallet pattern), so ballots,
 * lists, and results never need a populate and survive later profile edits.
 * The publish fingerprint (head hash + ballot/roll counts) freezes the
 * chain's state at the moment results went live — members compare against it
 * to confirm nothing changed afterwards.
 */

const candidateSchema = new Schema(
  {
    /** Stable public id — generated by the core on add, preserved across edits.
     *  Ballots reference this (not the ObjectId), so removing and re-adding a
     *  candidate can't silently inherit old votes. */
    id: { type: String, required: true },
    /** The member running for office — snapshot source, never displayed raw */
    userId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    /** Candidate identity snapshot (refreshed on every config save) */
    name: { type: String, required: true, trim: true },
    studentId: { type: String, required: true, trim: true },
    /** Session start year as a string, e.g. '2018' — key into src/data/batches.ts */
    batch: { type: String, required: true },
    /** Cloudinary URL of the candidate's profile photo ('' when none) */
    photo: { type: String, default: '' },
  },
  { _id: false }
);

const electionSchema = new Schema(
  {
    title: { type: String, required: true, trim: true, maxlength: 120 },
    description: { type: String, trim: true, maxlength: 600, default: '' },
    /** Stored lifecycle — the EFFECTIVE status additionally folds in the
     *  schedule window (src/lib/election.ts effectiveStatus). Manual actions
     *  write this field and always win over the schedule. */
    status: { type: String, enum: ELECTION_STATUSES, default: 'draft' },
    /** Optional schedule — when set, the window opens/closes itself at these
     *  instants (server-evaluated; manual open/close still overrides). */
    openAt: { type: Date, default: null },
    closeAt: { type: Date, default: null },
    /** Stamps of the manual lifecycle actions (audit + display) */
    openedAt: { type: Date, default: null },
    closedAt: { type: Date, default: null },
    publishedAt: { type: Date, default: null },
    /** Chain fingerprint frozen at publish — shown on /vote so members can
     *  confirm the ledger hasn't changed since results went live. */
    publishedHeadHash: { type: String, default: null },
    publishedBallotCount: { type: Number, default: null },
    publishedRollCount: { type: Number, default: null },
    /** The ballot's candidate slate */
    candidates: { type: [candidateSchema], default: [] },
  },
  { timestamps: true }
);

// /vote and the dashboard always load the newest election
electionSchema.index({ createdAt: -1 });

// Never leak internals through JSON
electionSchema.set('toJSON', {
  transform: (_doc, ret) => {
    const clean = ret as Record<string, unknown>;
    delete clean.__v;
    return ret;
  },
});

export type ElectionDocument = InferSchemaType<typeof electionSchema>;

const Election =
  (mongoose.models.Election as Model<ElectionDocument> | undefined) ??
  mongoose.model<ElectionDocument>('Election', electionSchema, 'elections');

export default Election;
